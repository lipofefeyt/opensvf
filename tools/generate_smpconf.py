#!/usr/bin/env python3
"""
Generate SMP-aligned assembly configuration XML from a spacecraft YAML.

SMP-style only: ECSS-E-ST-40-07C configuration files are .smpcfg documents
valid against XML/Smdl/Configuration.xsd; this output is not.

The output references model types defined in smp/opensvf.smpcat and
declares one Instance per equipment entry in the spacecraft configuration.
Wiring connections marked 'auto: true' are noted as a comment; explicit
wiring YAML connections are emitted as Connect elements.

Usage:
    python3 tools/generate_smpconf.py mission_mysat1/spacecraft.yaml \
        > smp/mysat1.smpconf
"""

import sys
from datetime import date
from pathlib import Path

import re

import yaml

sys.path.insert(0, str(Path(__file__).parent.parent / "src"))

from svf.smp.interfaces import SMP_ALIGNED_NS
from svf.srdb.definitions import Classification
from svf.srdb.loader import SrdbLoader


def _load_srdb() -> object:
    loader = SrdbLoader()
    for baseline in sorted(Path("srdb/baseline").glob("*.yaml")):
        loader.load_baseline(baseline)
    return loader.build()


def _infer_domain(srdb: object, equipment_id: str) -> str:
    """Return the SRDB domain (first name segment) for the given equipment id.

    Tries the exact id first, then falls back to stripping trailing digits
    (e.g. 'mag1' -> 'mag') for models registered under a base subsystem name.
    """
    from svf.srdb.loader import Srdb
    db: Srdb = srdb  # type: ignore[assignment]

    candidates = [equipment_id, re.sub(r"\d+$", "", equipment_id)]
    for candidate in candidates:
        for name in db.parameter_names:
            parts = name.split(".")
            if len(parts) >= 2 and parts[1] == candidate:
                return parts[0]
    return "unknown"


def _xml_escape(text: str) -> str:
    return (
        text.replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace('"', "&quot;")
    )


def generate_smpconf(spacecraft_yaml: Path, srdb: object) -> str:
    """
    Build an SMP-aligned Assembly XML string from a spacecraft YAML and loaded Srdb.

    Each equipment entry becomes an Instance whose TypeName references the
    corresponding Model in the opensvf SMP-aligned catalogue.
    """
    with spacecraft_yaml.open() as f:
        config = yaml.safe_load(f)

    spacecraft_name = _xml_escape(str(config.get("spacecraft", spacecraft_yaml.stem)))
    equipment_list  = config.get("equipment", [])
    wiring_cfg      = config.get("wiring", {})
    auto_wiring     = isinstance(wiring_cfg, dict) and wiring_cfg.get("auto", False)

    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!--',
        f'  opensvf SMP-aligned assembly configuration: {spacecraft_name}',
        '  Generated by tools/generate_smpconf.py',
        f'  Date: {date.today().isoformat()}',
        '  Aligned with: ECSS-E-ST-40-07C (Simulation Modelling Platform)',
        '  Not SMDL-conformant: not valid against XML/Smdl/Configuration.xsd',
        '  Types resolved from: smp/opensvf.smpcat',
        '-->',
        '<Assembly',
        f'  xmlns="{SMP_ALIGNED_NS}"',
        f'  Name="{spacecraft_name}"',
        '  Creator="opensvf tools/generate_smpconf.py"',
        f'  Date="{date.today().isoformat()}">',
        '',
        '  <Instances>',
    ]

    for entry in equipment_list:
        eq_id  = str(entry.get("id", ""))
        domain = _infer_domain(srdb, eq_id)
        type_name = f"opensvf.{domain}.{eq_id}"
        lines.append(f'    <Instance Name="{eq_id}" TypeName="{type_name}"/>')

    lines += [
        '  </Instances>',
        '',
        '  <Connections>',
    ]

    if auto_wiring:
        lines.append(
            '    <!-- auto-wiring: WiringLoader resolves connections at runtime'
            ' from SRDB port names -->'
        )
    else:
        wiring_file = wiring_cfg if isinstance(wiring_cfg, str) else None
        if wiring_file:
            wiring_path = spacecraft_yaml.parent / wiring_file
            if wiring_path.exists():
                with wiring_path.open() as wf:
                    wiring = yaml.safe_load(wf)
                for conn in wiring.get("connections", []):
                    src = _xml_escape(str(conn.get("from", "")))
                    dst = _xml_escape(str(conn.get("to", "")))
                    desc = _xml_escape(str(conn.get("description", "")))
                    comment = f' <!-- {desc} -->' if desc else ''
                    lines.append(f'    <Connect From="{src}" To="{dst}"/>{comment}')

    lines += [
        '  </Connections>',
        '',
        '</Assembly>',
    ]

    return "\n".join(lines)


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print(
            "Usage: python3 tools/generate_smpconf.py <spacecraft.yaml>",
            file=sys.stderr,
        )
        sys.exit(1)

    srdb = _load_srdb()
    print(generate_smpconf(Path(sys.argv[1]), srdb))
