#!/usr/bin/env python3
"""
Generate an SMP-aligned model catalogue XML from the opensvf SRDB.

The output is SMP-style (ECSS-E-ST-40-07C §4.10.1), grouping parameters by spacecraft domain (Package) and subsystem (Model).
SRDB TM parameters map to Kind="Output" fields; TC parameters to Kind="Input".

Usage:
    python3 tools/generate_smpcat.py > smp/opensvf.smpcat

It documents opensvf model interfaces without running the Python code. It is
not an SMDL catalogue: it does not conform to XML/Smdl/Catalogue.xsd (no
Namespace/Type elements, UUIDs or links to ecss.smp.smpcat), so SMP runtimes
(BASILES, EuroSim, SIMSAT) cannot load it. See roadmap item M68.
"""

import sys
from collections import defaultdict
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent / "src"))

from svf.smp.interfaces import SMP_ALIGNED_NS
from svf.srdb.definitions import Classification
from svf.srdb.loader import SrdbLoader


def _load_srdb() -> "Srdb":  # type: ignore[name-defined]
    loader = SrdbLoader()
    for baseline in sorted(Path("srdb/baseline").glob("*.yaml")):
        loader.load_baseline(baseline)
    return loader.build()


def _xml_escape(text: str) -> str:
    return (
        text.replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace('"', "&quot;")
    )


def generate_smpcat(srdb: object) -> str:
    """
    Build an SMP-aligned Catalogue XML string from a loaded Srdb.

    Grouping rules:
      - First name segment  (e.g. 'aocs')         -> Package
      - Second name segment (e.g. 'mag1')          -> Model within Package
      - Remaining segments  (e.g. 'field_x')       -> Field Name within Model
      - Classification TM -> Kind="Output"
      - Classification TC -> Kind="Input"
    """
    from svf.srdb.loader import Srdb  # local to avoid circular at module level

    db: Srdb = srdb  # type: ignore[assignment]

    # domain -> model -> [ParameterDefinition]
    tree: dict[str, dict[str, list]] = defaultdict(lambda: defaultdict(list))

    for name in sorted(db.parameter_names):
        param = db.get(name)
        if param is None:
            continue
        parts = name.split(".")
        domain = parts[0]
        model  = parts[1] if len(parts) > 1 else parts[0]
        tree[domain][model].append(param)

    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!--',
        '  opensvf SMP-aligned model catalogue',
        '  Generated by tools/generate_smpcat.py',
        f'  Date: {date.today().isoformat()}',
        '  Aligned with: ECSS-E-ST-40-07C (Simulation Modelling Platform)',
        '  Not SMDL-conformant: not valid against XML/Smdl/Catalogue.xsd',
        '-->',
        '<Catalogue',
        f'  xmlns="{SMP_ALIGNED_NS}"',
        '  xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"',
        '  Title="opensvf model catalogue"',
        '  Creator="opensvf tools/generate_smpcat.py"',
        f'  Date="{date.today().isoformat()}"',
        '  Version="1.0.0">',
        '',
        '  <Package Name="opensvf" Creator="opensvf">',
    ]

    for domain in sorted(tree):
        lines.append(f'')
        lines.append(f'    <Package Name="{domain}">')

        for model in sorted(tree[domain]):
            lines.append(f'      <Model Name="{model}">')

            for param in tree[domain][model]:
                parts    = param.name.split(".")
                field_name = ".".join(parts[2:]) if len(parts) > 2 else parts[-1]
                kind     = (
                    "Output" if param.classification == Classification.TM
                    else "Input"
                )
                unit     = _xml_escape(param.unit) if param.unit else ""
                desc     = _xml_escape(param.description)

                attrs = f'Name="{field_name}" Type="Float64" Kind="{kind}"'
                if unit:
                    attrs += f' Unit="{unit}"'
                if desc:
                    attrs += f' Description="{desc}"'

                lines.append(f'        <Field {attrs}/>')

            lines.append(f'      </Model>')

        lines.append(f'    </Package>')

    lines += [
        '',
        '  </Package>',
        '',
        '</Catalogue>',
    ]

    return "\n".join(lines)


if __name__ == "__main__":
    srdb = _load_srdb()
    print(generate_smpcat(srdb))
